def t(lang: str, key: str, **kwargs: object) -> str:
    """Return a translated string, falling back to English then the key."""
    pack = TRANSLATIONS.get(lang) or TRANSLATIONS["en"]
    text = pack.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text
